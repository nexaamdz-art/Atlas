    latin_words = set()
    for c in concepts:
        matches = re.findall(r'[a-zA-Z]+', c.get('name_ar', ''))
        for m in matches:
            latin_words.add(m)

    print(f"Remaining Latin words in Arabic: {len(latin_words)}")
    if latin_words:
        print("Leftovers:", sorted(latin_words))

def translate_phrase(text):
    """Translate an anatomical phrase into French and Arabic"""
    text_clean = text.strip()
    text_lower = text_clean.lower()
    
    # Check exact match first
    if text_lower in EXACT_CONCEPTS:
        return EXACT_CONCEPTS[text_lower]
        
    # Split by ' of ' (A of B -> B's A in AR, A de B in FR)
    if ' of ' in text_lower:
        parts = text_clean.split(' of ')
        fr_parts = []
        ar_parts = []
        for i, p in enumerate(parts):
            fr_sub, ar_sub = translate_phrase(p)
            fr_parts.append(fr_sub)
            if i == 0:
                # In Arabic, the first part of an Idafa structure is indefinite
                if ar_sub.startswith('ال') and len(ar_sub) > 2 and not ar_sub.startswith(('الذي', 'التي')):
                    ar_sub = ar_sub[2:]
                ar_parts.append(ar_sub)
            else:
                # Ensure subsequent part has 'ال' in Arabic
                if not ar_sub.startswith('ال'):
                    ar_sub = 'ال' + ar_sub
                ar_parts.append(ar_sub)
                
        # Combine French with 'de' / "de l'"
        fr_res = fr_parts[0]
        for sub in fr_parts[1:]:
            first = sub[0].lower() if sub else ''
            if first in 'aeiouéèêh':
                fr_res += f" de l'{sub}"
            else:
                fr_res += f" du {sub}" if not sub.lower().startswith('la ') else f" de {sub}"
        
        ar_res = " ".join(ar_parts)
        return (fr_res, ar_res)

    # Tokenize words
    words = re.findall(r'[a-zA-Z0-9]+', text_clean)
    if not words:
        return (text, text)
        
    fr_words = []
    ar_words = []
    
    # Reorganize order: In English adjectives precede nouns (e.g. "anterior descending branch")
    # In French: "Branche descendante antérieure" (noun first, then adjectives)
    # In Arabic: "الفرع النازل الأمامي" (noun with AL first, then adjectives with AL)
    
    # Identify head noun: usually the last word or one of the known nouns
    nouns_list = [
        "tree", "artery", "vein", "branch", "nerve", "muscle", "bone", "joint", 
        "ligament", "tendon", "organ", "system", "tract", "nucleus", "ganglion", 
        "plexus", "canal", "duct", "arch", "ring", "cord", "cavity", "fossa", 
        "sulcus", "fissure", "foramen", "sinus", "atrium", "ventricle", "valve", 
        "cusp", "leaflet", "plate", "disk", "sac", "bursa", "fold", "head", 
        "neck", "body", "base", "apex", "segment", "lobe", "lobule", "root",
        "trunk", "crest", "spine", "process", "tubercle", "condyle", "surface",
        "border", "margin", "wall", "septum", "space", "line", "sheath", "fascia",
        "membrane", "capsule", "cartilage", "cortex", "medulla", "substance",
        "matter", "apparatus", "entity", "structure", "component", "set", "zone",
        "region", "sector", "division", "extremity", "limb", "skeleton", "girdle",
        "column", "cage", "meatus", "hiatus", "orifice", "peduncle", "colliculus",
        "gyrus", "chiasm", "decussation", "corpus", "crus", "fasciae", "lamina",
        "stria", "anastomosis", "variability", "concha", "ampulla", "fundus"
    ]
    
    noun_idx = -1
    for i in range(len(words)-1, -1, -1):
        if words[i].lower() in nouns_list:
            noun_idx = i
            break
            
    if noun_idx != -1 and len(words) > 1:
        # Move noun to front for French
        noun_w = words[noun_idx]
        adjs_w = words[:noun_idx] + words[noun_idx+1:]
        
        # Translate noun
        n_lower = noun_w.lower()
        fr_n, ar_n = VOCAB.get(n_lower, (noun_w, noun_w))
        
        # Translate adjectives
        fr_a_list = []
        ar_a_list = []
        for a in adjs_w:
            a_lower = a.lower()
            fa, aa = VOCAB.get(a_lower, (a, a))
            if fa:
                fr_a_list.append(fa)
            if aa:
                # Add AL- prefix to adjectives in Arabic if not present and noun has it
                if not aa.startswith('ال') and len(aa) > 1 and not aa.isdigit():
                    aa = 'ال' + aa
                ar_a_list.append(aa)
                
        # Build French: Noun + Adjectives
        fr_res = f"{fr_n} {' '.join(fr_a_list)}".strip()
        fr_res = fr_res[0].upper() + fr_res[1:] if fr_res else ''
        
        # Build Arabic: Noun (def) + Adjectives (def)
        if not ar_n.startswith('ال') and not ar_n.isdigit():
            ar_n = 'ال' + ar_n
        ar_res = f"{ar_n} {' '.join(ar_a_list)}".strip()
        
        return (fr_res, ar_res)
    else:
        # Direct word by word
        for w in words:
            wl = w.lower()
            fw, aw = VOCAB.get(wl, (w, w))
            if fw:
                fr_words.append(fw)
            if aw:
                ar_words.append(aw)
                
        fr_res = " ".join(fr_words).strip()
        fr_res = fr_res[0].upper() + fr_res[1:] if fr_res else ''
        
        ar_res = " ".join(ar_words).strip()
        if ar_res and not ar_res.startswith('ال') and not ar_res.isdigit() and ' ' not in ar_res:
            ar_res = 'ال' + ar_res
            
        return (fr_res, ar_res)

